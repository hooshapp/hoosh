/** Build-only generator; private workspace isolates its TypeScript 5 peer from the app's TS 6. */
import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const input = new URL('../contracts/openapi/foundation.openapi.json', import.meta.url);
const output = new URL('../contracts/src/http.generated.ts', import.meta.url);
const args = process.argv.slice(2);
if (args.some((arg) => arg !== '--check')) throw new Error('Only --check is supported.');
const schema = JSON.parse(await readFile(input, 'utf8'));
const pending = [schema];
while (pending.length) {
  const value = pending.pop();
  if (!value || typeof value !== 'object') continue;
  if ('$ref' in value && (typeof value.$ref !== 'string' || !value.$ref.startsWith('#/'))) {
    throw new Error('Foundation generation accepts local schema references only.');
  }
  pending.push(...Object.values(value));
}
const ast = await openapiTS(schema);
const text = '/**\n * Generated by openapi-typescript 7.13.0 from foundation.openapi.json.\n'
  + ' * Do not edit. Run npm run api:generate and review schema/types together.\n */\n'
  + astToString(ast);
if (args.includes('--check')) {
  let current;
  try { current = await readFile(output, 'utf8'); } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (current !== text) throw new Error('HTTP type drift: run npm run api:generate.');
  process.stdout.write('Generated HTTP types match the pinned generator and schema.\n');
} else {
  await writeFile(output, text);
  process.stdout.write('Generated packages/contracts/src/http.generated.ts\n');
}
